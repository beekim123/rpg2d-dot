import {test,expect} from '@playwright/test';
import {maps,walkTo,traverse,face} from './world-controls.ts';
import words from '../../content/i18n/zh-Hans/ui.json' with {type:'json'};

test('native investigation and NPC dialogue respond to real keyboard and mouse without moving the player',async({page})=>{
  test.setTimeout(60000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('/');const canvas=page.locator('#canvas');
  await expect(canvas).toHaveAttribute('data-ready','true',{timeout:30000});await canvas.click();
  const home=maps['lv.finn_house']!,town=maps['lv.town']!;
  await walkTo(page,home,home.spawn,{x:4,y:7});await face(page,'ArrowUp','up');
  await page.keyboard.press('KeyZ');
  await expect(canvas).toHaveAttribute('data-dialogue_active','true');
  await expect(canvas).toHaveAttribute('data-dialogue_script','lv.inspect.finn_bed');
  await expect(canvas).toHaveAttribute('data-speaker','芬恩');
  await page.keyboard.down('ArrowRight');await page.waitForTimeout(250);await page.keyboard.up('ArrowRight');
  await expect(canvas).toHaveAttribute('data-grid_x','4');await expect(canvas).toHaveAttribute('data-grid_y','7');
  await page.keyboard.press('KeyX');await expect(canvas).toHaveAttribute('data-dialogue_revealed','true');
  await page.screenshot({path:'artifacts/screenshots/godot-g1-investigation.png'});
  const box=await canvas.boundingBox();expect(box).not.toBeNull();
  await canvas.click({position:{x:box!.width*.75,y:box!.height*.82}});
  await expect(canvas).toHaveAttribute('data-dialogue_active','false');
  const arrival=await traverse(page,home,{x:4,y:7},'lv.town');
  await walkTo(page,town,arrival,{x:18,y:11});await face(page,'ArrowUp','up');
  await page.keyboard.press('Enter');await expect(canvas).toHaveAttribute('data-dialogue_active','true');
  await expect(canvas).toHaveAttribute('data-speaker','霍伯');
  await page.keyboard.press('KeyX');await expect(canvas).toHaveAttribute('data-dialogue_text',words['lv.npc.hob.day.01']);
  await page.screenshot({path:'artifacts/screenshots/godot-g1-dialogue-hob.png'});
  await page.keyboard.press('Space');await expect(canvas).toHaveAttribute('data-speaker','芬恩');
  await page.keyboard.press('KeyX');await expect(canvas).toHaveAttribute('data-dialogue_text',words['lv.npc.hob.day.02']);
  await page.keyboard.press('KeyZ');await expect(canvas).toHaveAttribute('data-dialogue_active','false');
  await page.keyboard.press('KeyZ');await expect(canvas).toHaveAttribute('data-dialogue_active','true');
  await page.keyboard.press('KeyX');await expect(canvas).toHaveAttribute('data-dialogue_text',words['lv.npc.hob.repeat.01']);
  await page.keyboard.press('KeyZ');await expect(canvas).toHaveAttribute('data-dialogue_active','false');
  await walkTo(page,town,{x:18,y:11},{x:17,y:11});
  await expect(canvas).toHaveAttribute('data-grid_x','17');
  expect(errors).toEqual([]);
});
