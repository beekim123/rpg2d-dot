import {test,expect} from '@playwright/test';
import {maps,traverse} from './world-controls.ts';
const home=maps['lv.finn_house']!;
test('Godot Web starts at home and real keys traverse paired doors without losing resources',async({page})=>{
  test.setTimeout(60000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('/');const canvas=page.locator('#canvas');
  await expect(canvas).toHaveAttribute('data-ready','true',{timeout:30000});
  await expect(canvas).toHaveAttribute('data-map_id','lv.finn_house');
  await expect(canvas).toHaveAttribute('aria-label',/芬恩家/);
  await expect(canvas).toHaveAttribute('data-grid_x','5');await expect(canvas).toHaveAttribute('data-grid_y','7');
  await page.screenshot({path:'artifacts/screenshots/godot-g1-home.png'});
  await canvas.click();
  let at=await traverse(page,maps['lv.finn_house']!,home.spawn,'lv.town');
  await expect(canvas).toHaveAttribute('aria-label',/灯谷镇/);
  await page.screenshot({path:'artifacts/screenshots/godot-g1-town.png'});
  at=await traverse(page,maps['lv.town']!,at,'lv.lamp_shop');
  await expect(canvas).toHaveAttribute('aria-label',/霍伯的灯铺/);
  await page.screenshot({path:'artifacts/screenshots/godot-g1-shop.png'});
  at=await traverse(page,maps['lv.lamp_shop']!,at,'lv.town');
  await traverse(page,maps['lv.town']!,at,'lv.finn_house');
  await expect(canvas).toHaveAttribute('aria-label',/芬恩家/);
  expect(errors).toEqual([]);
});
