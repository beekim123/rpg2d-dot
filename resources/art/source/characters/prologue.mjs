function makeCharacter(id, bases, width, height, patches) {
  const frames = [], animations = {};
  for (const [direction, base] of Object.entries({ ...bases, right: bases.left.map(row => [...row].reverse().join('')) })) {
    const offset = frames.length;
    const edit = (changes = []) => {
      const rows = base.map(row => [...row]);
      for (const [x, y, color] of changes) rows[y][direction === 'right' ? width - 1 - x : x] = color;
      return rows.map(row => row.join(''));
    };
    const side = direction === 'right' ? 'left' : direction;
    frames.push(base, edit(patches[side].breath), edit(patches[side].sway), edit(patches[side].blink));
    // Alternating planted foot, passing stance, opposite planted foot, second
    // passing stance. Every pose retains the same logical bottom-centre anchor.
    const leftFoot = width === 24 ? 8 : 5, rightFoot = width === 24 ? 13 : 9;
    frames.push(
      edit([[leftFoot - 1, height - 3, 'I'], [leftFoot - 1, height - 2, 'J'], [rightFoot + 1, height - 1, '.'], ...patches[side].breath]),
      edit([[leftFoot, height - 3, 'A'], [rightFoot, height - 3, 's']]),
      edit([[rightFoot + 1, height - 3, 'I'], [rightFoot + 1, height - 2, 'J'], [leftFoot - 1, height - 1, '.'], ...patches[side].sway]),
      edit([[leftFoot, height - 3, 's'], [rightFoot, height - 3, 'A']]),
    );
    animations[`idle_${direction}`] = { frames: idleTicks.map(frame => offset + frame), fps: 4, loop: true };
    animations[`walk_${direction}`] = { frames: [4, 5, 6, 7].map(frame => offset + frame), fps: 8, loop: true };
  }
  animations.idle = animations.idle_down;
  // Append reaction poses without changing any map idle or walk index. The
  // shoulders and guarding hand change, while the bottom five rows stay exact.
  const reactions = id === 'char.ella' ? [
    { x: 2, y: 10, rows: ['..AAA...', '.AvvuA..', '.AvtihA.', '..AihhA.', '...AAAA.'], cells: [[6, 6, 'g'], [9, 6, 'g']] },
    { x: 2, y: 11, rows: ['.AAA....', 'AvvuA...', 'AvtiiA..', '.AAihA..', '..AAAA..'], cells: [[6, 6, 'g'], [9, 6, 'g']] },
  ] : id === 'char.shade' ? [
    { x: 13, y: 15, rows: ['..AAA...', '.AtvuA..', 'AtvvuA..', 'AuuAA...', '.AAA....', '..AkBA..', '..AkBA..', '..AAAA..'], cells: [[7, 15, 'k'], [8, 15, 'A']] },
    { x: 14, y: 16, rows: ['..AA...', '.AtuA..', 'AtvuA..', 'AuuA...', '.AAA...', '..BA...'], cells: [[7, 15, 'B'], [8, 15, 'k']] },
  ] : [
    { x: 2, y: 10, rows: ['..AAA...', '.AtuuA..', '.AuuiA..', '..AihA..', '...AAA..'], cells: [[6, 7, 'G'], [7, 7, 'h']] },
    { x: 2, y: 11, rows: ['.AAA....', '.AtuA...', '.AuuiA..', '..AihA..', '...AAA..'], cells: [[6, 7, 'H'], [7, 7, 'h']] },
  ];
  for (const reaction of reactions) {
    const pose = bases.down.map(row => [...row]);
    reaction.rows.forEach((row, dy) => [...row].forEach((color, dx) => { pose[reaction.y + dy][reaction.x + dx] = color; }));
    for (const [x, y, color] of reaction.cells) pose[y][x] = color;
    frames.push(pose.map(row => row.join('')));
  }
  animations.hurt = { frames: [32, 33], fps: 10, loop: false };
  return {
    meta: { id, kind: 'pixel', category: 'character', size: [width, height], anchor: [width / 2, height], frames: frames.length, animations },
    draw(g, { frame }) { frames[frame].forEach((row, y) => [...row].forEach((color, x) => g.px(x, y, color))); },
  };
}

